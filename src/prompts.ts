const pickRandom = <T>(items: readonly T[]): T => {
  const index = Math.floor(Math.random() * items.length);
  return items[index] as T;
};

export const buildRandomPrompt = (): string => {
  const base = pickRandom(CAT_PROMPTS);
  const extra = pickRandom(RANDOM_WORDS);
  return `${base}, ${extra}`;
};
